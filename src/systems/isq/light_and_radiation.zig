const qs = @import("../../lib/quantity_spec.zig");
const base = @import("base.zig");
const em = @import("electromagnetism.zig");
const mc = @import("mechanics.zig");
const si = @import("si_quantities.zig");
const st = @import("space_and_time.zig");

pub const SpeedOfLightInAMedium = qs.ChildQuantitySpec("speed of light in a medium", st.Speed);
pub const RefractiveIndex = qs.ChildQuantitySpecWithEquation("refractive index", base.Dimensionless, em.SpeedOfLightInVacuum.Div(SpeedOfLightInAMedium));
pub const RadiantEnergy = qs.ChildQuantitySpec("radiant energy", si.Energy);
pub const SpectralRadiantEnergy = qs.DerivedQuantitySpec("spectral radiant energy", RadiantEnergy.Div(st.Wavelength));
pub const RadiantEnergyDensity = qs.DerivedQuantitySpec("radiant energy density", RadiantEnergy.Div(st.Volume));
pub const SpectralRadiantEnergyDensityInTermsOfWavelength = qs.DerivedQuantitySpec("spectral radiant energy density in terms of wavelength", RadiantEnergyDensity.Div(st.Wavelength));
pub const SpectralRadiantEnergyDensityInTermsOfWavenumber = qs.DerivedQuantitySpec("spectral radiant energy density in terms of wavenumber", RadiantEnergyDensity.Div(st.Wavenumber));
pub const RadiantFlux = qs.ChildQuantitySpecWithEquation("radiant flux", mc.Power, RadiantEnergy.Div(base.Time));
pub const RadiantPower = RadiantFlux;
pub const SpectralRadiantFlux = qs.DerivedQuantitySpec("spectral radiant flux", RadiantFlux.Div(st.Wavelength));
pub const SpectralRadiantPower = SpectralRadiantFlux;
pub const RadiantIntensity = qs.DerivedQuantitySpec("radiant intensity", RadiantFlux.Div(si.SolidAngularMeasure));
pub const SpectralRadiantIntensity = qs.DerivedQuantitySpec("spectral radiant intensity", RadiantIntensity.Div(st.Wavelength));
pub const Radiance = qs.DerivedQuantitySpec("radiance", RadiantIntensity.Div(si.Area));
pub const SpectralRadiance = qs.DerivedQuantitySpec("spectral radiance", Radiance.Div(st.Wavelength));
pub const Irradiance = qs.DerivedQuantitySpec("irradiance", RadiantFlux.Div(si.Area));
pub const SpectralIrradiance = qs.DerivedQuantitySpec("spectral irradiance", Irradiance.Div(st.Wavelength));
pub const RadiantExitance = qs.DerivedQuantitySpec("radiant exitance", RadiantFlux.Div(si.Area));
pub const SpectralRadiantExitance = qs.DerivedQuantitySpec("spectral radiant exitance", RadiantExitance.Div(st.Wavelength));
pub const RadiantExposure = qs.DerivedQuantitySpec("radiant exposure", RadiantEnergy.Div(si.Area));
pub const SpectralRadiantExposure = qs.DerivedQuantitySpec("spectral radiant exposure", RadiantExposure.Div(st.Wavelength));
